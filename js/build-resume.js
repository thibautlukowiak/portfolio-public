// Build cv/index.html and 404.html (resume only) from index.html
const fs = require('fs')
const path = require('path')

const root = path.join(__dirname, '..')
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8')
const url = 'https://thibautlukowiak.com/cv/'

const extract = (start, end) => {
  const from = html.indexOf(start)
  const to = html.indexOf(end, from)
  if (from === -1 || to === -1) throw new Error(`Resume: "${start}" not found in index.html`)
  return html.slice(from, to + end.length)
}

// Absolute paths (pages not at the root)
const absolutePaths = (content) => content.replace(/(href|src)="(scss|js|img)\//g, '$1="/$2/')

const setMeta = (head, attribute, name, content) =>
  head.replace(new RegExp(`(${attribute}="${name}"\\s+content=")[^"]*(")`), `$1${content}$2`)

const baseHead = absolutePaths(extract('<head>', '</head>'))

// Header: back to the site + name
const header = extract('<header>', '</header>')
  .replace(/\s*<button[\s\S]*?<\/button>/g, '')
  .replace('class="main-nav"', 'class="main-nav main-nav--single"')
  .replace(
    '<a href="/" class="header__link">',
    `<a href="/" class="back-link hide-print" aria-label="Retour au site"><span class="icon-arrow icon-arrow--left" aria-hidden="true"></span></a>
        <a href="/" class="header__link">`
  )

const resume = extract('<section id="resume"', '</section>')
  .replace(/\s*<li class="resume__link[\s\S]*?<\/li>/, '')

const page = (head, title, pageHeader = header) => `<!DOCTYPE html>
<!-- Generated by js/build-resume.js from index.html: do not edit -->
<html lang="fr">
  ${head}

  <body class="resume-display">
    ${pageHeader}

    <main id="content" class="wrapper">
      ${resume.replace(
        '<h2 id="resume-title" class="sr-only">Curriculum vitae</h2>',
        `<h2 id="resume-title" class="sr-only">${title}</h2>`
      )}
    </main>

    <script>
      document.querySelector('.js-print').addEventListener('click', () => window.print())
    </script>
  </body>
</html>
`

// Resume page
const title = 'CV de Thibaut Lukowiak | UX Designer &amp; Développeur Front'
const description =
  'CV de Thibaut Lukowiak, UX designer et développeur front à Paris : design systems from scratch, Figma, HTML, SCSS, JS, Vue.js. Missions pour Corsair, LittleBig Connection, MisterFly, TUI...'

let cvHead = baseHead.replace(/<title>.*?<\/title>/, `<title>${title}</title>`)
cvHead = setMeta(cvHead, 'name', 'description', description)
cvHead = setMeta(cvHead, 'property', 'og:title', title)
cvHead = setMeta(cvHead, 'property', 'og:description', description)
cvHead = setMeta(cvHead, 'property', 'og:url', url)
cvHead = cvHead.replace(/<link rel="canonical" href="[^"]*" \/>/, `<link rel="canonical" href="${url}" />`)

fs.mkdirSync(path.join(root, 'cv'), { recursive: true })
fs.writeFileSync(path.join(root, 'cv/index.html'), page(cvHead, 'Curriculum vitae'))
console.log('cv/index.html generated')

// 404 page: not indexed, message instead of the job
const job = '<span class="header__job">UX Designer &amp; Développeur Front</span>'
const notFoundHeader = header.replace(
  job,
  `<span class="header__job header__job--message hide-print">La page que vous cherchez n'existe pas mais voici mon CV</span>
            ${job.replace('header__job', 'header__job for-print')}`
)
if (notFoundHeader === header) throw new Error('404: job title not found in the header')

const notFoundHead = baseHead
  .replace(/<title>.*?<\/title>/, '<title>Page introuvable | Thibaut Lukowiak | CV</title>')
  .replace(/\s*<link rel="canonical" href="[^"]*" \/>/, '\n    <meta name="robots" content="noindex" />')

fs.writeFileSync(path.join(root, '404.html'), page(notFoundHead, 'Page introuvable, voici mon CV', notFoundHeader))
console.log('404.html generated')
